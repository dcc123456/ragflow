// goldenBox mirrors one entry of a *.boxes.golden.json fixture: a synthetic
// OCR box whose rect equals one assembled TSR cell, carrying the deterministic
// label "cell_i" used by gen_vh_table_golden.py.
type goldenBox struct {
	Text   string  `json:"text"`
	X0     float64 `json:"x0"`
	Top    float64 `json:"top"`
	X1     float64 `json:"x1"`
	Bottom float64 `json:"bottom"`
}

// TestVHTableParity proves the Go EE V/H pipeline (Assemble ->
// ConstructTableVH) reproduces the 0.26.4 deepdoc/vision/tsr.py
// construct_table HTML for every corpus fixture, using the committed
// vh_table.golden.json (produced by gen_vh_table_golden.py against the real
// 0.26.4 tsr.py) as the expected output.
//
// The golden HTML was generated by Python from the same wire (the fixture's
// *.golden.json) and the same synthetic boxes (*.boxes.golden.json), so the
// test reuses that exact offline oracle rather than re-running Python.
// ConstructTableVH mirrors tsr.py construct_table precisely (IoU>=0.85 text
// overlay + geometric flow), so the two render the same ragged table. The
// comparison is structural (ParseTableHTML -> TableData.Grid) so attribute
// quoting differences do not cause false mismatches.
//
// This is the offline, deterministic equivalence guarantee between Go EE and
// Python EE table construction. The corpus golden is a local generated
// artifact (gitignored); the test Skips when it is absent instead of failing.
func TestVHTableParity(t *testing.T) {
	corpus := filepath.Join("..", "..", "..", "native", "testdata", "tsr_ee_parity", "corpus")
	goldRaw, err := os.ReadFile(filepath.Join(corpus, "vh_table.golden.json"))
	if err != nil {
		t.Skipf("corpus golden unavailable: %v", err)
	}
	var gold map[string]string
	if err := json.Unmarshal(goldRaw, &gold); err != nil {
		t.Fatalf("parse vh_table golden: %v", err)
	}
	if len(gold) == 0 {
		t.Skip("empty vh_table golden")
	}

	for name, exp := range gold {
		name, exp := name, exp
		t.Run(name, func(t *testing.T) {
			wireRaw, err := os.ReadFile(filepath.Join(corpus, name+".golden.json"))
			if err != nil {
				t.Skipf("wire golden missing for %s: %v", name, err)
				return
			}
			var wire struct {
				Bboxes [][]float64 `json:"bboxes"`
			}
			if err := json.Unmarshal(wireRaw, &wire); err != nil {
				t.Fatalf("parse wire %s: %v", name, err)
			}
			cells := make([]pdf.TSRCell, 0, len(wire.Bboxes))
			for _, b := range wire.Bboxes {
				if len(b) < 5 {
					continue
				}
				cells = append(cells, pdf.TSRCell{X0: b[0], Y0: b[1], X1: b[2], Y1: b[3], Score: b[4]})
			}

			// imgH mirrors TestVHAssemblyParity: Assemble needs the image
			// height only for an edge-case bottom-row extension.
			imgH := 0.0
			if f, err := os.Open(filepath.Join(corpus, name+".png")); err == nil {
				if img, err := png.Decode(f); err == nil {
					imgH = float64(img.Bounds().Dy())
				}
				f.Close()
			}

			assembled := VHTableAssembler{}.Assemble(cells, imgH)

			boxRaw, err := os.ReadFile(filepath.Join(corpus, name+".boxes.golden.json"))
			if err != nil {
				t.Skipf("boxes golden missing for %s: %v", name, err)
				return
			}
			var gboxes []goldenBox
			if err := json.Unmarshal(boxRaw, &gboxes); err != nil {
				t.Fatalf("parse boxes %s: %v", name, err)
			}
			boxes := make([]pdf.TextBox, len(gboxes))
			for i, gb := range gboxes {
				boxes[i] = pdf.TextBox{X0: gb.X0, Top: gb.Top, X1: gb.X1, Bottom: gb.Bottom, Text: gb.Text}
			}

			// Go EE V/H pipeline: Assemble then construct_table-equivalent
			// (IoU>=0.85 overlay + geometric flow).
			got := ConstructTableVH(assembled, boxes, "")

			if exp == "" {
				if got != "" {
					t.Errorf("%s: expected empty table, got %q", name, got)
				}
				return
			}
			gotTD, err := tableutil.ParseTableHTML(got)
			if err != nil {
				t.Fatalf("parse got %s: %v", name, err)
			}
			expTD, err := tableutil.ParseTableHTML(exp)
			if err != nil {
				t.Fatalf("parse exp %s: %v", name, err)
			}
			if !reflect.DeepEqual(gotTD.Grid, expTD.Grid) {
				t.Errorf("%s: grid mismatch\ngot=%s\n\nexp=%s", name, got, exp)
			}
		})
	}
}

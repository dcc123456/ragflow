const generatedPrefix = "zz_eestub_"
const generatedHeader = "// Code generated by eestub. DO NOT EDIT."

type sourceFile struct {
	name      string
	file      *ast.File
	fset      *token.FileSet
	imports   map[string]*ast.ImportSpec
	stub      bool
	shared    bool
	active    bool
	community bool
}

type declaration struct {
	file *sourceFile
	fn   *ast.FuncDecl
}

type generatedFile struct {
	data   []byte
	issues []declarationIssue
}

func main() {
	root := flag.String("root", ".", "repository root")
	dryRun := flag.Bool("dry-run", false, "report without writing or removing generated files")
	base := flag.String("base-ref", os.Getenv("EESTUB_BASE_SHA"), "base commit used to identify new and pre-existing issues")
	summary := flag.String("summary", os.Getenv("GITHUB_STEP_SUMMARY"), "append a Markdown provenance summary to this file")
	flag.Parse()
	dirs := flag.Args()
	if len(dirs) == 0 {
		dirs = []string{"cmd", "internal"}
	}
	opts := reportOptions{baseRef: *base, summaryPath: *summary, repository: os.Getenv("GITHUB_REPOSITORY"), upstream: "infiniflow/ragflow", apiURL: os.Getenv("GITHUB_API_URL"), token: os.Getenv("GH_TOKEN")}
	if err := runCheck(*root, dirs, !*dryRun, os.Stdout, opts); err != nil {
		fmt.Fprintln(os.Stderr, "eestub:", err)
		os.Exit(1)
	}
}

// Match the common build.sh build/test environment. sonic-only declarations
// are treated as conditional implementations, rather than shadowed by a fallback.
func enterpriseContext() build.Context {
	ctx := build.Default
	ctx.BuildTags = []string{"static", "ee"}
	return ctx
}

func runCheck(root string, dirs []string, write bool, out io.Writer, opts reportOptions) error {
	var report bytes.Buffer
	out = io.MultiWriter(out, &report)
	fmt.Fprintln(out, "Enterprise Stub Compatibility Report")
	var packages []string
	var failures []error
	var issues []declarationIssue
	seen := map[string]bool{}
	for _, dir := range dirs {
		err := filepath.WalkDir(filepath.Join(root, dir), func(name string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() {
				if strings.HasPrefix(entry.Name(), ".") && name != filepath.Join(root, dir) || entry.Name() == "testdata" || entry.Name() == "vendor" {
					return filepath.SkipDir
				}
				return nil
			}
			if entry.Name() != "stub.go" && !strings.HasSuffix(entry.Name(), "_stub.go") && !(strings.HasPrefix(entry.Name(), generatedPrefix) && strings.HasSuffix(entry.Name(), "_ee.go")) {
				return nil
			}
			pkg := filepath.Dir(name)
			if !seen[pkg] {
				seen[pkg] = true
				packages = append(packages, pkg)
			}
			return nil
		})
		if err != nil {
			fmt.Fprintf(out, "ERROR %s: %v\n", dir, err)
			failures = append(failures, err)
		}
	}
	sort.Strings(packages)
	for _, dir := range packages {
		if err := generatePackage(root, dir, write, out, &issues); err != nil {
			fmt.Fprintf(out, "ERROR %s: %v\n", dir, err)
			failures = append(failures, fmt.Errorf("%s: %w", dir, err))
		}
	}
	text := report.String()
	generated := strings.Count(text, "\nGENERATED ")
	missing := strings.Count(text, "\nMISSING ")
	mismatched := strings.Count(text, "\nMISMATCH ")
	unsupported := strings.Count(text, "\nUNSUPPORTED ")
	warnings, blocking := 0, 0
	for _, issue := range issues {
		if issue.isWarning() {
			warnings++
		} else {
			blocking++
		}
	}
	fmt.Fprintf(out, "\nScanned packages: %d\nMatched declarations: %d\nMissing EE hooks: %d\nSignature mismatches: %d\nUnsupported declarations: %d\nGenerated panic fallbacks: %d\nWarnings: %d\nScan errors: %d\n", len(packages), strings.Count(text, "\nEXISTS "), generated+missing, mismatched, unsupported, generated, warnings, len(failures))
	if err := reportIssues(root, issues, opts, out); err != nil {
		failures = append(failures, err)
	}
	if blocking > 0 {
		failures = append(failures, fmt.Errorf("%d blocking hook issues require resolution; generated panic fallbacks do not satisfy the check", blocking))
	}
	if len(failures) > 0 {
		fmt.Fprintln(out, "Result: FAILED. Full scan completed; resolve blocking hook issues and rerun CI.")
		return errors.Join(failures...)
	}
	if warnings > 0 {
		fmt.Fprintln(out, "Result: PASSED WITH WARNINGS. No blocking EE hook gaps found within the scan scope.")
	} else {
		fmt.Fprintln(out, "Result: PASSED. No enterprise implementation gaps found within the scan scope.")
	}
	return nil
}

func readPackage(dir string) ([]*sourceFile, []string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	ee := enterpriseContext()
	oss := ee
	oss.BuildTags = []string{"static"}
	var files []*sourceFile
	var generated []string
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, nil, err
		}
		if strings.HasPrefix(name, generatedPrefix) && bytes.HasPrefix(data, []byte(generatedHeader+"\n")) {
			if entry.Type()&os.ModeSymlink != 0 {
				return nil, nil, fmt.Errorf("refusing generated symlink %s", name)
			}
			generated = append(generated, name)
			continue
		}
		community, err := oss.MatchFile(dir, name)
		if err != nil {
			return nil, nil, err
		}
		enterprise, err := ee.MatchFile(dir, name)
		if err != nil {
			return nil, nil, err
		}
		source, err := parseSource(name, data)
		if err != nil {
			return nil, nil, err
		}
		source.stub = community && !enterprise && (name == "stub.go" || strings.HasSuffix(name, "_stub.go"))
		source.shared, source.active = community && enterprise, enterprise
		source.community = community
		files = append(files, source)
	}
	return files, generated, nil
}

func parseSource(name string, data []byte) (*sourceFile, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, name, data, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	source := &sourceFile{name: name, file: file, fset: fset, imports: map[string]*ast.ImportSpec{}}
	for _, spec := range file.Imports {
		importPath, _ := strconv.Unquote(spec.Path.Value)
		alias := path.Base(importPath)
		if strings.HasPrefix(alias, "v") && len(alias) > 1 && alias[1] >= '0' && alias[1] <= '9' {
			alias = path.Base(path.Dir(importPath))
		}
		alias = strings.Split(alias, ".")[0]
		if spec.Name != nil {
			alias = spec.Name.Name
		}
		source.imports[alias] = spec
	}
	return source, nil
}

func generatePackage(root, dir string, write bool, out io.Writer, issues *[]declarationIssue) error {
	files, oldGenerated, err := readPackage(dir)
	if err != nil {
		return err
	}
	active := map[string]declaration{}
	conditional := map[string]bool{}
	names := map[string]bool{}
	typeNames := map[string]bool{}
	references := map[string]bool{}
	for _, source := range files {
		if source.shared {
			// Local variables are resolved by go/parser. Unresolved identifiers
			// can refer to package declarations in other files. Qualified imports
			// must not make an unrelated community helper into a contract.
			ast.Inspect(source.file, func(node ast.Node) bool {
				if selector, ok := node.(*ast.SelectorExpr); ok {
					if id, ok := selector.X.(*ast.Ident); ok && id.Obj == nil && source.imports[id.Name] != nil {
						return false
					}
				}
				if id, ok := node.(*ast.Ident); ok && id.Obj == nil {
					references[id.Name] = true
				}
				return true
			})
		}
		for _, decl := range source.file.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok {
				key := functionKey(fn)
				if source.active {
					active[key] = declaration{source, fn}
					if fn.Recv == nil {
						names[fn.Name.Name] = true
					}
				} else if !source.stub {
					conditional[key] = true
				}
			}
			if gen, ok := decl.(*ast.GenDecl); ok && source.active {
				for _, spec := range gen.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						names[spec.Name.Name] = true
						typeNames[spec.Name.Name] = spec.Assign == token.NoPos && spec.TypeParams == nil
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							names[name.Name] = true
						}
					}
				}
			}
		}
	}
	outputs := map[string]generatedFile{}
	communityBodies := newImplementationClassifier(files)
	label, _ := filepath.Rel(root, dir)
	for _, source := range files {
		if !source.stub {
			continue
		}
		var fallbacks []*ast.FuncDecl
		var pending []declarationIssue
		usedImports := map[string]bool{}
		for _, decl := range source.file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Name.Name == "init" || !ast.IsExported(fn.Name.Name) && !references[fn.Name.Name] {
				continue
			}
			key := functionKey(fn)
			newIssue := func(status, reason string) declarationIssue {
				issue := declarationIssue{kind: status, symbol: filepath.ToSlash(label) + "." + key, file: filepath.ToSlash(filepath.Join(label, source.name)), source: source, fn: fn, reason: reason}
				if real, exists := active[key]; exists {
					issue.ee = &real
				}
				return issue
			}
			report := func(status, detail string) {
				fmt.Fprintf(out, "%s %s.%s: %s (%s)\n", status, filepath.ToSlash(label), key, detail, source.name)
				if status != "EXISTS" {
					*issues = append(*issues, newIssue(status, detail))
				}
			}
			if real, exists := active[key]; exists {
				if signature(fn, source) != signature(real.fn, real.file) {
					report("MISMATCH", "existing signature differs; left unchanged: "+real.file.name)
				} else {
					report("EXISTS", real.file.name)
				}
				continue
			}
			if fn.Recv == nil && names[fn.Name.Name] {
				report("MISMATCH", "name belongs to a non-function declaration; left unchanged")
				continue
			}
			switch communityBodies.classify(fn, source) {
			case concreteImplementation:
				report("OSS_IMPLEMENTED", "community hook has an implementation; no EE fallback generated")
				continue
			case uncertainImplementation:
				report("REVIEW", "community hook body cannot be classified reliably; no EE fallback generated")
				continue
			}
			if conditional[key] {
				report("UNSUPPORTED", "declaration exists under other build constraints")
				continue
			}
			imports, reason := fallbackDependencies(fn, source, names, typeNames)
			if reason != "" {
				report("UNSUPPORTED", reason)
				continue
			}
			if !write {
				report("MISSING", "would generate panic fallback")
				continue
			}
			for alias := range imports {
				usedImports[alias] = true
			}
			copy := *fn
			copy.Doc = nil
			copy.Type = cloneType(fn.Type).(*ast.FuncType)
			if fn.Recv != nil {
				copy.Recv = &ast.FieldList{List: []*ast.Field{{Type: cloneType(fn.Recv.List[0].Type)}}}
			}
			copy.Body = &ast.BlockStmt{List: []ast.Stmt{
				&ast.ExprStmt{X: &ast.CallExpr{Fun: ast.NewIdent("panic"), Args: []ast.Expr{
					&ast.BasicLit{Kind: token.STRING, Value: strconv.Quote("missing enterprise implementation: " + filepath.ToSlash(label) + "." + key)},
				}}},
			}}
			fallbacks = append(fallbacks, &copy)
			pending = append(pending, newIssue("GENERATED", ""))
		}
		if len(fallbacks) == 0 {
			continue
		}
		name := generatedPrefix + strings.TrimSuffix(source.name, ".go") + "_ee.go"
		file := &ast.File{Name: ast.NewIdent(source.file.Name.Name)}
		var aliases []string
		for alias := range usedImports {
			aliases = append(aliases, alias)
		}
		sort.Strings(aliases)
		if len(aliases) > 0 {
			imports := &ast.GenDecl{Tok: token.IMPORT}
			for _, alias := range aliases {
				imports.Specs = append(imports.Specs, source.imports[alias])
			}
			file.Decls = append(file.Decls, imports)
		}
		for _, fn := range fallbacks {
			file.Decls = append(file.Decls, fn)
		}
		var buf bytes.Buffer
		ctx := enterpriseContext()
		cgo := "!cgo"
		if ctx.CgoEnabled {
			cgo = "cgo"
		}
		fmt.Fprintf(&buf, "%s\n\n//go:build ee && %s && %s && %s && static\n\n", generatedHeader, ctx.GOOS, ctx.GOARCH, cgo)
		if err := format.Node(&buf, token.NewFileSet(), file); err != nil {
			return err
		}
		data, err := format.Source(buf.Bytes())
		if err != nil {
			return err
		}
		output := generatedFile{data: data, issues: pending}
		for i := range output.issues {
			output.issues[i].generated = filepath.ToSlash(filepath.Join(label, name))
		}
		outputs[name] = output
	}
	if !write {
		return nil
	}
	for name := range outputs {
		if info, err := os.Lstat(filepath.Join(dir, name)); err == nil {
			data, readErr := os.ReadFile(filepath.Join(dir, name))
			if info.Mode()&os.ModeSymlink != 0 || readErr != nil || !bytes.HasPrefix(data, []byte(generatedHeader+"\n")) {
				return fmt.Errorf("refusing to overwrite %s", name)
			}
		} else if !os.IsNotExist(err) {
			return err
		}
	}
	for _, name := range oldGenerated {
		if err := os.Remove(filepath.Join(dir, name)); err != nil {
			return err
		}
	}
	var outputNames []string
	for name := range outputs {
		outputNames = append(outputNames, name)
	}
	sort.Strings(outputNames)
	for _, name := range outputNames {
		output := outputs[name]
		if err := os.WriteFile(filepath.Join(dir, name), output.data, 0644); err != nil {
			return err
		}
		for _, issue := range output.issues {
			fmt.Fprintf(out, "GENERATED %s: panic fallback (%s)\n", issue.symbol, name)
			*issues = append(*issues, issue)
		}
	}
	return nil
}

func functionKey(fn *ast.FuncDecl) string {
	if fn.Recv == nil {
		return fn.Name.Name
	}
	receiver := fn.Recv.List[0].Type
	if pointer, ok := receiver.(*ast.StarExpr); ok {
		receiver = pointer.X
	}
	return printNode(receiver) + "." + fn.Name.Name
}

func printNode(node ast.Node) string {
	var buf bytes.Buffer
	_ = format.Node(&buf, token.NewFileSet(), node)
	return buf.String()
}

// Clone before removing names, so neither the source AST nor the declarations
// used for generation are changed while comparing signatures.
func cloneType(expr ast.Expr) ast.Expr {
	copy, err := parser.ParseExpr(printNode(expr))
	if err != nil {
		panic(err) // expr came from a successfully parsed Go file.
	}
	ast.Inspect(copy, func(node ast.Node) bool {
		if fn, ok := node.(*ast.FuncType); ok {
			for _, fields := range []*ast.FieldList{fn.Params, fn.Results} {
				if fields == nil {
					continue
				}
				var list []*ast.Field
				for _, field := range fields.List {
					count := max(1, len(field.Names))
					for range count {
						list = append(list, &ast.Field{Type: field.Type})
					}
				}
				fields.List = list
			}
		}
		return true
	})
	return copy
}

func signature(fn *ast.FuncDecl, source *sourceFile) string {
	normalize := func(expr ast.Expr) string {
		copy := cloneType(expr)
		ast.Inspect(copy, func(node ast.Node) bool {
			if selector, ok := node.(*ast.SelectorExpr); ok {
				if id, ok := selector.X.(*ast.Ident); ok {
					if spec := source.imports[id.Name]; spec != nil {
						id.Name = spec.Path.Value
					}
				}
			}
			return true
		})
		return printNode(copy)
	}
	result := normalize(fn.Type)
	if fn.Recv != nil {
		result = normalize(fn.Recv.List[0].Type) + ":" + result
	}
	return result
}

func fallbackDependencies(fn *ast.FuncDecl, source *sourceFile, names, typeNames map[string]bool) (map[string]bool, string) {
	if fn.Type.TypeParams != nil {
		return nil, "generic functions are not generated"
	}
	constraint := ""
	for _, group := range source.file.Comments {
		for _, comment := range group.List {
			if strings.HasPrefix(comment.Text, "//go:build ") {
				constraint = strings.TrimSpace(strings.TrimPrefix(comment.Text, "//go:build "))
			}
		}
	}
	if constraint != "!ee" {
		return nil, "only a plain //go:build !ee stub can be generated"
	}
	if source.imports["."] != nil {
		return nil, "dot imports cannot be resolved safely"
	}
	if names["panic"] || fn.Name.Name == "panic" {
		return nil, "package shadows the builtin panic"
	}
	if fn.Recv != nil {
		receiver := fn.Recv.List[0].Type
		if pointer, ok := receiver.(*ast.StarExpr); ok {
			receiver = pointer.X
		}
		name, ok := receiver.(*ast.Ident)
		if !ok || !typeNames[name.Name] {
			return nil, "receiver type is missing or generic"
		}
	}
	used := map[string]bool{}
	reason := ""
	var check func(ast.Expr)
	checkFields := func(fields *ast.FieldList) {
		if fields != nil {
			for _, field := range fields.List {
				check(field.Type)
			}
		}
	}
	check = func(expr ast.Expr) {
		if expr == nil || reason != "" {
			return
		}
		switch expr := expr.(type) {
		case *ast.Ident:
			_, local := typeNames[expr.Name]
			_, builtin := types.Universe.Lookup(expr.Name).(*types.TypeName)
			if !local && !builtin {
				reason = "missing signature dependency: " + expr.Name
			}
		case *ast.SelectorExpr:
			id, ok := expr.X.(*ast.Ident)
			if !ok || source.imports[id.Name] == nil {
				reason = "unresolved qualified signature type"
				return
			}
			if id.Name == "panic" {
				reason = "signature import shadows the builtin panic"
				return
			}
			if source.imports[id.Name].Path.Value == `"C"` {
				reason = "cgo signature types require their original preamble"
				return
			}
			used[id.Name] = true
		case *ast.StarExpr:
			check(expr.X)
		case *ast.ArrayType:
			// Array lengths can refer to constants, rather than types. Avoid
			// evaluating expressions or importing packages to infer a value.
			if expr.Len != nil { // Slices have no length expression.
				ast.Inspect(expr.Len, func(node ast.Node) bool {
					if id, ok := node.(*ast.Ident); ok && !names[id.Name] {
						reason = "unresolved array length: " + id.Name
					}
					return true
				})
			}
			check(expr.Elt)
		case *ast.MapType:
			check(expr.Key)
			check(expr.Value)
		case *ast.ChanType:
			check(expr.Value)
		case *ast.Ellipsis:
			check(expr.Elt)
		case *ast.FuncType:
			checkFields(expr.Params)
			checkFields(expr.Results)
		case *ast.StructType:
			checkFields(expr.Fields)
		case *ast.InterfaceType:
			checkFields(expr.Methods)
		case *ast.ParenExpr:
			check(expr.X)
		case *ast.BasicLit:
		case *ast.BinaryExpr:
			check(expr.X)
			check(expr.Y)
		case *ast.UnaryExpr:
			check(expr.X)
		default:
			reason = "unsupported signature expression (including generic types)"
		}
	}
	check(fn.Type)
	return used, reason
}
